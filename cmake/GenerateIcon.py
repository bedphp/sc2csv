"""Build every icon the application uses from the one source image, icon/ico.png.

Usage: GenerateIcon.py <source.png> <about_header.h> <output_dir>

<output_dir> receives the two files rc.exe needs:

    sc2csv.ico   multi-size Windows icon (16, 24, 32, 48, 64, 128, 256 px), embedded in the executable
    sc2csv.rc    the resource script that names it (IDI_APPICON 101)

<about_header.h> receives the 128 px PNG the About panel draws (64 pt at 2x) as a byte array.
"""
import io
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # Pillow ships with the build environment; without it the committed header is used.
    sys.exit("Pillow is required to build the icon (pip install pillow)")

ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)
ABOUT_SIZE = 128
RESOURCE_ID = 101

source = Path(sys.argv[1])
about_header = Path(sys.argv[2])
output_dir = Path(sys.argv[3])

image = Image.open(source).convert("RGBA")

output_dir.mkdir(parents=True, exist_ok=True)

# Pillow renders one ICO member per size; Windows picks the closest one for Explorer, the taskbar and Alt+Tab. The
# 256 px member is stored as PNG by the ICO writer, which Vista and later read.
ico_path = output_dir / "sc2csv.ico"
image.save(ico_path, format="ICO", sizes=[(size, size) for size in ICO_SIZES])

# rc.exe resolves the .ico path relative to the .rc file, so writing both in the same directory is enough.
(output_dir / "sc2csv.rc").write_text(
    "// Generated by cmake/GenerateIcon.py from icon/ico.png. Do not edit; the build regenerates it.\n"
    "#include <windows.h>\n\n"
    f"#define IDI_APPICON {RESOURCE_ID}\n"
    'IDI_APPICON ICON "sc2csv.ico"\n',
    encoding="utf-8",
)

# The About panel draws its copy with Cupertino::LoadBitmap, which takes an encoded PNG.
about = image.resize((ABOUT_SIZE, ABOUT_SIZE), Image.LANCZOS)
buffer = io.BytesIO()
about.save(buffer, format="PNG", optimize=True)
data = buffer.getvalue()

lines = [
    f"// Generated from {source.name} ({ABOUT_SIZE} x {ABOUT_SIZE}, drawn by the About panel at {ABOUT_SIZE // 2} pt).",
    "// Do not edit; the build regenerates it from icon/ico.png, see cmake/GenerateIcon.py.",
    "#pragma once",
    "",
    "#include <cstddef>",
    "",
    "namespace sc2csv {",
    "",
    "inline constexpr unsigned char kAboutIconPng[] = {",
]
for start in range(0, len(data), 12):
    lines.append("    " + ", ".join(f"0x{byte:02x}u" for byte in data[start:start + 12]) + ",")
lines += [
    "};",
    "inline constexpr std::size_t kAboutIconPngSize = sizeof(kAboutIconPng);",
    "",
    "} // namespace sc2csv",
    "",
]
about_header.write_text("\n".join(lines), encoding="utf-8")

print(f"wrote {ico_path} ({', '.join(str(size) for size in ICO_SIZES)} px)")
print(f"baked {len(data)} bytes into {about_header}")
